import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
process.on('uncaughtException', error => { console.error(error.message); process.exitCode=1; });
const run = (cmd, args) => {
  const result = spawnSync(cmd,args,{stdio:'inherit'});
  if (result.status !== 0) throw new Error(`${cmd} failed. Hosting setup stopped.`);
};
// Finish installation before changing working routes.
run('npm',['install','@convex-dev/static-hosting@0.2.1']);
const configPath='convex/convex.config.ts';
if (existsSync(configPath) && !readFileSync(configPath,'utf8').includes('@convex-dev/static-hosting')) {
  throw new Error('A Convex component config already exists. Merge static hosting into that config before continuing.');
}
writeFileSync(configPath,`import { defineApp } from "convex/server";
import staticHosting from "@convex-dev/static-hosting/convex.config";
const app = defineApp();
// Keep Gmail OAuth and private ledger routes at their existing addresses.
app.use(staticHosting);
export default app;
`);
const httpPath='convex/http.ts';
let http=readFileSync(httpPath,'utf8');
if (!http.includes('registerStaticRoutes')) {
  if (!http.includes('http.route({ path: "/", method: "GET"')) throw new Error('The Home route changed; hosting setup needs review.');
  http=http.replace('import { internal } from "./_generated/api";', 'import { internal, components } from "./_generated/api";\nimport { registerStaticRoutes } from "@convex-dev/static-hosting";');
  http=http.replace('http.route({ path: "/", method: "GET"','http.route({ path: "/home", method: "GET"');
  http=http.replace('export default http;', `http.route({ path: "/session", method: "GET", handler: httpAction(async (_ctx, request) => {
  // No private data is sent to the public screen, just whether this browser is connected.
  return new Response(null, { status: await owner(request) ? 204 : 401, headers: { "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff" } });
}) });
// Exact Gmail, salary and transaction routes take precedence over the static files.
registerStaticRoutes(http, components.staticHosting, { spaFallback: false });
export default http;`);
  writeFileSync(httpPath,http);
}
// This type is normally regenerated by convex dev; add it for the first local check.
const apiPath='convex/_generated/api.d.ts';
if (existsSync(apiPath)) {
  let api=readFileSync(apiPath,'utf8');
  if (api.includes('export declare const components: {};')) {
    api=api.replace('export declare const components: {};', 'export declare const components: { staticHosting: import("@convex-dev/static-hosting/_generated/component").ComponentApi<"staticHosting"> };');
    writeFileSync(apiPath,api);
  }
}
run('npm',['run','build']);
run('npm',['run','check']);
run('npm',['test']);
console.log('Static hosting is configured. Run npm run deploy to upload to the existing Convex development app.');
